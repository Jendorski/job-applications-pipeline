"""tracker.md and tracker.csv: read-only views regenerated from the database after every change."""

import csv
from pathlib import Path

from jap.db import DB, PIPELINE_STATUSES, USER_STATUSES

COLUMNS = ["id", "status", "company", "title", "track", "location", "remote", "created", "applied", "cost_usd", "note", "folder", "url"]
ORDER = ["ready", "needs_review", "needs_manual_jd", "failed", "paused_budget", *USER_STATUSES,
         *[s for s in PIPELINE_STATUSES if s not in ("ready", "needs_review", "needs_manual_jd", "failed", "paused_budget")]]


def _row(job: dict) -> dict:
    return {
        "id": f"{job['id']:04d}", "status": job["status"], "company": job["company"] or "", "title": job["title"] or "",
        "track": job["track"] or "", "location": job["location"] or "", "remote": job["remote"] or "",
        "created": job["created_at"][:10], "applied": (job["applied_at"] or "")[:10],
        "cost_usd": f"{job['cost_usd']:.3f}", "note": job["note"] or job["error"] or "",
        "folder": job["folder"] or "", "url": job["primary_url"],
    }


def write_tracker(db: DB, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = [_row(j) for j in db.jobs()]

    with open(out_dir / "tracker.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)

    lines = ["# Applications", "", "Generated by `jap`; change statuses with `jap mark <id> <status>`.", ""]
    for status in ORDER:
        group = [r for r in rows if r["status"] == status]
        if not group:
            continue
        lines += [f"## {status} ({len(group)})", "", "| id | company | role | track | created | applied | note |",
                  "|---|---|---|---|---|---|---|"]
        for r in group:
            role = f"[{r['title'] or r['url']}]({r['folder']}/)" if r["folder"] else (r["title"] or r["url"])
            note = r["note"].replace("|", "\\|").replace("\n", " ")[:120]
            lines.append(f"| {r['id']} | {r['company']} | {role} | {r['track']} | {r['created']} | {r['applied']} | {note} |")
        lines.append("")
    (out_dir / "tracker.md").write_text("\n".join(lines))
